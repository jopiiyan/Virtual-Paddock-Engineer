"""F1 race data -> LangChain Documents -> Supabase pgvector.

Sources (both free, no login): OpenF1 for per-lap timing + tyre stints, Jolpica for
classified results. FastF1 used to be the source, but F1's livetiming server now
requires an F1TV sign-in (401) — see backend/f1data.py.
"""

import os

import numpy as np
import pandas as pd
from langchain_core.documents import Document
from supabase import create_client

from backend.f1data import jolpica_race_results, openf1, openf1_session_key
from backend.vectorstore import get_embedder

# Same rule FastF1's pick_quicklaps() applied: drop laps slower than 107% of the
# session's fastest lap (safety-car, in/out and traffic-wrecked laps).
QUICKLAP_THRESHOLD = 1.07


SESSION_LABELS = {"R": "Race", "Q": "Qualifying", "S": "Sprint", "FP1": "Practice 1",
                  "FP2": "Practice 2", "FP3": "Practice 3"}


def stint_chunk_id(year: int, gp: str, session_type: str, driver: str, stint: int) -> str:
    """Deterministic, re-ingest-stable id for a stint document.

    The DB `id` is an autogenerated bigserial that changes on every re-ingest, so
    it can't anchor the golden eval set's `relevant_chunk_ids` (would break R6
    determinism). This id is derived purely from the data identity instead, so the
    same stint always resolves to the same chunk id. Keep this format in lockstep
    with scripts/backfill_chunk_ids.py.
    """
    return f"{year}_{gp}_{session_type}_{driver}_stint{stint}"


def result_chunk_id(year: int, gp: str, session_type: str, driver: str) -> str:
    """Deterministic, re-ingest-stable id for a race-result document."""
    return f"{year}_{gp}_{session_type}_{driver}_result"


def fmt_laptime(td) -> str:
    """Format a lap-time Timedelta as M:SS.sss (e.g. 1:28.412)."""
    total = td.total_seconds()
    minutes, seconds = divmod(total, 60)
    return f"{int(minutes)}:{seconds:06.3f}"


def fmt_sector(td) -> str:
    """Format a sector Timedelta as SS.sss seconds, or 'n/a' if missing."""
    if td is None or pd.isna(td):
        return "n/a"
    return f"{td.total_seconds():.3f}s"


def trap_speed(stint_laps, col) -> str:
    """Max speed (km/h) seen at one speed trap over the stint, or 'n/a'."""
    val = pd.to_numeric(stint_laps[col], errors="coerce").max()
    return f"{int(round(val))} km/h" if np.isfinite(val) else "n/a"


def load_quicklaps(year: int, gp: str, session_type: str = "R") -> pd.DataFrame:
    """OpenF1 laps for one session, tagged with driver code / stint / compound,
    in the same column names the document builder used with FastF1."""
    session_name = SESSION_LABELS.get(session_type, session_type)
    key = openf1_session_key(year, gp, session_name)

    codes = {d["driver_number"]: d["name_acronym"] for d in openf1("drivers", session_key=key)}
    stints = openf1("stints", session_key=key)
    laps = pd.DataFrame(openf1("laps", session_key=key))

    def stint_of(row):
        for s in stints:
            if (s["driver_number"] == row["driver_number"]
                    and s["lap_start"] <= row["lap_number"] <= (s["lap_end"] or 10**6)):
                return s["stint_number"], (s["compound"] or "UNKNOWN")
        return None, None

    laps[["Stint", "Compound"]] = laps.apply(stint_of, axis=1, result_type="expand")
    laps["Driver"] = laps["driver_number"].map(codes)
    laps = laps.dropna(subset=["lap_duration", "Stint", "Driver"])
    laps = laps[~laps["is_pit_out_lap"].astype(bool)]
    laps = laps[laps["lap_duration"] <= laps["lap_duration"].min() * QUICKLAP_THRESHOLD]

    secs = lambda col: pd.to_timedelta(pd.to_numeric(laps[col], errors="coerce"), unit="s")
    return laps.assign(
        LapNumber=laps["lap_number"],
        LapTime=secs("lap_duration"),
        Sector1Time=secs("duration_sector_1"),
        Sector2Time=secs("duration_sector_2"),
        Sector3Time=secs("duration_sector_3"),
        SpeedI1=laps["i1_speed"], SpeedI2=laps["i2_speed"], SpeedST=laps["st_speed"],
    )


def build_stint_documents(year: int, gp: str, session_type: str = "R") -> list[Document]:
    laps = load_quicklaps(year, gp, session_type)

    docs = []
    for driver in laps["Driver"].unique():
        driver_laps = laps[laps["Driver"] == driver]
        for stint_num, stint_laps in driver_laps.groupby("Stint"):
            if len(stint_laps) < 3:        # too short to say anything useful
                continue

            compound = stint_laps["Compound"].iloc[0]

            # Lap-time stats over the stint (Timedelta → "M:SS.sss")
            avg_laptime = fmt_laptime(stint_laps["LapTime"].mean())
            best_laptime = fmt_laptime(stint_laps["LapTime"].min())

            # Average sector times — decomposes the lap to show WHERE pace is found.
            s1 = fmt_sector(stint_laps["Sector1Time"].mean())
            s2 = fmt_sector(stint_laps["Sector2Time"].mean())
            s3 = fmt_sector(stint_laps["Sector3Time"].mean())

            # Per-trap max speeds (km/h). ST is the main straight-line trap.
            # (OpenF1 has no finish-line trap, so FL from the FastF1 era is gone.)
            i1, i2 = trap_speed(stint_laps, "SpeedI1"), trap_speed(stint_laps, "SpeedI2")
            st = trap_speed(stint_laps, "SpeedST")

            # Degradation = slope of lap time (s) vs lap number, i.e. seconds lost per lap.
            # Positive slope = tyres slowing down over the stint.
            fit = stint_laps[["LapNumber", "LapTime"]].dropna()
            if len(fit) >= 2:
                x = fit["LapNumber"].to_numpy(dtype=float)
                y = fit["LapTime"].dt.total_seconds().to_numpy(dtype=float)
                degradation = float(np.polyfit(x, y, 1)[0])
            else:
                degradation = 0.0

            session_label = SESSION_LABELS.get(session_type, session_type)
            summary = (
                f"In the {year} {gp} {session_label}, {driver} ran stint {int(stint_num)} "
                f"on {compound} tyres over {len(stint_laps)} laps. "
                f"Average lap {avg_laptime}, best lap {best_laptime}. "
                f"Average sector times: S1 {s1}, S2 {s2}, S3 {s3}. "
                f"Top speeds at the traps: I1 {i1}, I2 {i2}, ST {st}. "
                f"Tyre degradation {degradation:+.3f} s/lap "
                f"({'tyres slowing' if degradation > 0 else 'pace holding/improving'})."
            )

            docs.append(Document(  ##always page_content and metadata
                page_content=summary,
                metadata={
                    "chunk_id": stint_chunk_id(year, gp, session_type, driver, int(stint_num)),
                    "driver": driver,           # 'HAM' — uppercase, matters for filtering
                    "year": year,
                    "grand_prix": gp,
                    "session_type": session_type,  # 'R'/'Q'/... — powers the session dropdown filter
                    "stint": int(stint_num),
                    "compound": compound,
                },
            ))
    return docs


def fmt_racetime(td) -> str | None:
    """Format the winner's total race time as H:MM:SS.sss (or M:SS.sss)."""
    if td is None or pd.isna(td):
        return None
    total = td.total_seconds()
    hours, rem = divmod(total, 3600)
    minutes, seconds = divmod(rem, 60)
    if hours:
        return f"{int(hours)}:{int(minutes):02d}:{seconds:06.3f}"
    return f"{int(minutes)}:{seconds:06.3f}"


def summary_chunk_id(year: int, gp: str, session_type: str) -> str:
    """Deterministic, re-ingest-stable id for a race-summary document."""
    return f"{year}_{gp}_{session_type}_summary"


def build_summary_document(year: int, gp: str, session_type: str = "R",
                           results: list[dict] | None = None) -> Document:
    """ONE Document per race covering the whole field: podium, full classification,
    points per team, fastest lap, retirements.

    Why: per-driver docs can't answer whole-field questions ("who was on the podium?",
    "which team scored most?") because retrieval only returns a handful of them, and
    similarity search doesn't know "podium" means P1-P3. One summary doc can.
    """
    session_label = SESSION_LABELS.get(session_type, session_type)
    results = results if results is not None else jolpica_race_results(year, gp)

    def who(r):
        return f'{r["Driver"]["code"].upper()} ({r["Driver"]["givenName"]} {r["Driver"]["familyName"]}, {r["Constructor"]["name"]})'

    finishers = [r for r in results if r["positionText"].isdigit()]
    finishers.sort(key=lambda r: int(r["position"]))
    retired = [r for r in results if not r["positionText"].isdigit()]

    team_points: dict[str, float] = {}
    for r in results:
        team_points[r["Constructor"]["name"]] = team_points.get(r["Constructor"]["name"], 0.0) + float(r["points"])
    teams = sorted(team_points.items(), key=lambda kv: -kv[1])

    fastest = next((r for r in results if r.get("FastestLap", {}).get("rank") == "1"), None)

    parts = [f"Race summary: {year} {gp} {session_label}."]
    if finishers:
        parts.append(f"Winner: {who(finishers[0])}.")
        parts.append("Podium: " + ", ".join(f"P{r['position']} {who(r)}" for r in finishers[:3]) + ".")
        parts.append("Full classification: " + "; ".join(
            f"P{r['position']} {r['Driver']['code'].upper()} ({r['Constructor']['name']}, "
            f"{float(r['points']):g} pts, from grid P{r['grid']})" for r in finishers) + ".")
    if retired:
        parts.append("Did not finish / not classified: " + "; ".join(
            f"{r['Driver']['code'].upper()} ({r['status']})" for r in retired) + ".")
    parts.append("Points by team: " + "; ".join(f"{t} {p:g}" for t, p in teams) + ".")
    if fastest:
        parts.append(f"Fastest lap: {who(fastest)}, {fastest['FastestLap']['Time']['time']} "
                     f"on lap {fastest['FastestLap']['lap']}.")

    return Document(
        page_content=" ".join(parts),
        metadata={
            "chunk_id": summary_chunk_id(year, gp, session_type),
            "year": year,
            "grand_prix": gp,
            "session_type": session_type,
            "doc_type": "summary",
        },
    )


def build_result_documents(year: int, gp: str, session_type: str = "R",
                           results: list[dict] | None = None) -> list[Document]:
    """One Document per driver giving their race finishing result.

    page_content is natural-language (winner / position / finishing time or gap /
    grid / points); metadata carries driver + grand_prix so it filters alongside
    the stint documents. The winner's row holds the total race time; everyone
    else's Time is the gap to the winner.
    """
    session_label = SESSION_LABELS.get(session_type, session_type)
    results = results if results is not None else jolpica_race_results(year, gp)
    # Jolpica gives every finisher an absolute race time in millis.
    winner_ms = int(results[0]["Time"]["millis"]) if results and "Time" in results[0] else None
    winner_time = fmt_racetime(pd.Timedelta(milliseconds=winner_ms)) if winner_ms else None

    docs = []
    for row in results:
        code = row["Driver"]["code"].upper()
        name = f'{row["Driver"]["givenName"]} {row["Driver"]["familyName"]}'
        team = row["Constructor"]["name"]
        status = row["status"]
        points = float(row["points"])
        grid = int(row["grid"])
        grid_txt = f" from grid P{grid}" if grid > 0 else " from the pit lane"
        points_txt = f", scoring {points:g} points"

        # positionText is a number only for classified finishers ('R', 'W', 'D' otherwise).
        finished = row["positionText"].isdigit()
        pos_int = int(row["position"]) if finished else None
        finish_ms = int(row["Time"]["millis"]) if "Time" in row else None

        if pos_int == 1:
            timing = f"won the race in a finishing time of {winner_time}" if winner_time else "won the race"
        elif finished and finish_ms and winner_ms:
            gap = (finish_ms - winner_ms) / 1000
            finish_time = fmt_racetime(pd.Timedelta(milliseconds=finish_ms))
            timing = f"finished P{pos_int} in a finishing time of {finish_time} (+{gap:.3f}s behind the winner)"
        elif finished:
            # Lapped cars have no time; status carries 'Lapped' / '+1 Lap'.
            timing = f"finished P{pos_int} ({status})"
        else:
            timing = f"did not finish (Status: {status})"

        summary = (
            f"In the {year} {gp} {session_label}, {code} ({name}, {team}) {timing}"
            f"{grid_txt}{points_txt}."
        )

        docs.append(Document(
            page_content=summary,
            metadata={
                "chunk_id": result_chunk_id(year, gp, session_type, code),
                "driver": code,
                "year": year,
                "grand_prix": gp,
                "session_type": session_type,
                "doc_type": "result",          # distinguishes result docs from stint docs
                "position": pos_int,
            },
        ))
    return docs


def embed_with_backoff(texts: list[str], batch: int = 20, max_waits: int = 10) -> list[list[float]]:
    """Embed in small batches; on a rate-limit (429) wait a minute and retry.

    Gemini's free tier counts each text as a request, so embedding a whole race
    at once trips the per-minute quota.
    """
    import time

    embedder = get_embedder()
    out: list[list[float]] = []
    for i in range(0, len(texts), batch):
        for attempt in range(max_waits + 1):
            try:
                out += embedder.embed_documents(texts[i:i + batch])
                break
            except Exception as exc:
                if "429" not in str(exc) or attempt == max_waits:
                    raise
                print(f"  rate-limited at doc {i}/{len(texts)}; waiting 60s...")
                time.sleep(60)
    return out


def main() -> None:
    # Optional: load a local .env if python-dotenv is installed.
    try:
        from dotenv import load_dotenv
        load_dotenv()
    except ModuleNotFoundError:
        pass

    supabase_url = os.environ["SUPABASE_URL"]
    supabase_key = os.environ["SUPABASE_SERVICE_KEY"]
    year = int(os.environ.get("INGEST_YEAR", "2025"))
    # One race or several, comma-separated, e.g. INGEST_GP="Suzuka,Sakhir,Barcelona".
    gps = [g.strip() for g in os.environ.get("INGEST_GP", "Silverstone").split(",") if g.strip()]

    supabase = create_client(supabase_url, supabase_key)
    for n, gp in enumerate(gps, 1):
        print(f"[{n}/{len(gps)}] {year} {gp}")
        ingest_race(supabase, year, gp)


def ingest_race(supabase, year: int, gp: str, session_type: str = "R") -> None:
    """Build, embed and store one race. Idempotent: replaces any rows already stored
    for the same (year, grand_prix, session_type), so re-running never duplicates."""
    results = jolpica_race_results(year, gp)
    docs = (build_stint_documents(year, gp, session_type)
            + build_result_documents(year, gp, session_type, results)
            + [build_summary_document(year, gp, session_type, results)])
    print(f"  built {len(docs)} documents (stints + results + 1 summary)")

    # Embed BEFORE deleting anything, so a failure (rate limit, API error) leaves
    # whatever was stored for this race untouched.
    embeddings = embed_with_backoff([d.page_content for d in docs])
    rows = [
        {"content": d.page_content, "metadata": d.metadata, "embedding": e}
        for d, e in zip(docs, embeddings)
    ]

    scope = {"year": year, "grand_prix": gp, "session_type": session_type}
    removed = supabase.table("documents").delete().contains("metadata", scope).execute().data
    if removed:
        print(f"  replaced {len(removed)} existing rows for this race")

    # Insert directly instead of SupabaseVectorStore.from_documents: the wrapper now
    # sends client-side UUIDs as `id`, which the bigserial primary key rejects.
    for i in range(0, len(rows), 100):
        supabase.table("documents").insert(rows[i:i + 100]).execute()
    print(f"  inserted {len(rows)} documents")


if __name__ == "__main__":
    main()
